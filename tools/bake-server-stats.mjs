#!/usr/bin/env node
// Precomputes the rating context the Edge Function needs, so it stops reading
// the whole player table to work it out again on every request.
//
// WHAT IT COSTS TODAY, measured against the live project:
//
//   12 isolate boots for 6 requests. Every isolate boots, serves one request
//   and dies, so DATASET_TTL_MS - a ten-minute in-memory cache - never once
//   survives to be used. It is not a cache, it is dead code.
//
//   So every request that reaches datasetStatsFor() pages in the entire table:
//   14,431 football rows at 6.72MB, or 10,290 basketball rows at 2.14MB. An
//   online match is two players each calling warm-up and then simulate, so a
//   single game of football costs about 19MB of database egress to compute a
//   number that has not changed since the last deploy.
//
// The context is a PURE FUNCTION OF THE DATASET. It is percentile
// distributions - what a good passer rates against every other passer - and
// the dataset changes when someone regenerates it, not when someone plays a
// game. So it is computed here, once, and committed.
//
//   football  6.72MB read -> 464KB baked
//   basketball 2.14MB read ->   1KB baked
//
// __allEntries IS DROPPED, and it is most of the football saving. The engine
// keeps every entry on the context for the draft-grade curve in
// js/sports/*/draftgrade.js, which runs in the BROWSER. The server writes 4.8MB
// of it per isolate and never reads a single row back.
//
// WHY THE OUTPUT IS COMMITTED RATHER THAN BUILT AT DEPLOY TIME. The deploy
// workflow triggers on `supabase/functions/**`. A generated-but-uncommitted
// tree would stop that trigger firing when the engine changes - the exact
// failure the vendoring exists to prevent, arrived at from the other
// direction. tools/vendor-engines.mjs makes the same argument at more length;
// this follows it, and `npm run verify:baked` is the check that says whether
// the committed copy is current, the way verify:vendored does for the engines.
//
//   node tools/bake-server-stats.mjs           # write
//   node tools/bake-server-stats.mjs --check   # compare, write nothing

import { build } from "esbuild";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { seedRowsFor } from "./lib/seed-rows.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FN = path.join(ROOT, "supabase", "functions", "simulate-match");
const CHECK_ONLY = process.argv.includes("--check");

/**
 * The server's OWN registry does the computing.
 *
 * Not a reimplementation of it here: normalizeNbaRow and generatedNflEntry are
 * small enough to copy and that is exactly why copying them would be a bad
 * idea - a copy that drifts produces statistics computed one way and served
 * another, and every number involved stays plausible. Bundling the real
 * sports/index.ts costs a second and removes the question.
 */
async function serverRegistry() {
  const dir = await mkdtemp(path.join(tmpdir(), "bk-bake-"));
  const outfile = path.join(dir, "sports.mjs");
  await build({
    entryPoints: [path.join(FN, "sports", "index.ts")],
    bundle: true,
    platform: "neutral",
    format: "esm",
    outfile,
    logLevel: "silent",
  });
  return import(pathToFileURL(outfile).href);
}

/** Stable key order, so a rebuild that changed nothing produces a byte-identical
 * file and `--check` means what it says. */
function stableStringify(value) {
  return JSON.stringify(value, (_key, v) => {
    if (v && typeof v === "object" && !Array.isArray(v)) {
      return Object.fromEntries(Object.keys(v).sort().map((k) => [k, v[k]]));
    }
    return v;
  });
}

export async function bakedFor(sportId, registry) {
  const engine = registry.engineFor(sportId);
  if (!engine) throw new Error(`no server engine for '${sportId}'`);
  const rows = await seedRowsFor(sportId);
  const stats = engine.computeDatasetStats(rows);
  // See the header: the browser's draft-grade curve wants these, the server
  // never touches them, and they are 4.8MB of the football context.
  delete stats.__allEntries;
  return {
    // The row count is the drift probe's whole basis. A `count(*)` is a header
    // and no payload, so the server can ask "is the table still the one these
    // numbers describe" for nothing.
    rowCount: rows.length,
    datasetVersion: engine.datasetVersion(rows),
    stats,
  };
}

function moduleSource(sportId, baked) {
  return (
    `// GENERATED by tools/bake-server-stats.mjs - do not edit.\n` +
    `//\n` +
    `// The rating context for ${sportId}, precomputed from the same rows the seed\n` +
    `// writes, so the Edge Function does not page the whole table in to derive it\n` +
    `// on every request. See that tool for why, and scripts/verify-baked-stats.mjs\n` +
    `// for the check that this is still current.\n` +
    `//\n` +
    `// ROW_COUNT is what the server compares a live count(*) against: if the table\n` +
    `// no longer holds this many rows, these statistics describe a pool that is\n` +
    `// gone and the server falls back to reading it properly.\n` +
    `export const ROW_COUNT = ${baked.rowCount};\n` +
    `export const DATASET_VERSION = ${JSON.stringify(baked.datasetVersion)};\n` +
    `export const STATS = ${stableStringify(baked.stats)};\n`
  );
}

const registry = await serverRegistry();
const sports = registry.supportedSports();
const results = [];
let stale = 0;

for (const sportId of sports) {
  const baked = await bakedFor(sportId, registry);
  const file = path.join(FN, "sports", sportId, "stats.generated.js");
  const next = moduleSource(sportId, baked);
  const current = await readFile(file, "utf8").catch(() => null);
  const same = current === next;
  if (!same) stale += 1;
  if (!same && !CHECK_ONLY) await writeFile(file, next);
  results.push({
    sportId,
    rows: baked.rowCount,
    version: baked.datasetVersion,
    bytes: Buffer.byteLength(next),
    same,
  });
}

for (const r of results) {
  const state = r.same ? "current" : CHECK_ONLY ? "STALE" : "written";
  console.log(
    `  ${r.sportId.padEnd(4)} ${String(r.rows).padStart(6)} rows  ` +
      `${(r.bytes / 1024).toFixed(0).padStart(4)}KB  ${r.version.padEnd(26)} ${state}`
  );
}

if (CHECK_ONLY && stale) {
  console.error(`\n${stale} baked stats file(s) are out of date - run \`npm run bake\`\n`);
  process.exit(1);
}
console.log(
  CHECK_ONLY
    ? `\n${results.length} baked stats file(s) current\n`
    : `\n${results.length - stale} already current, ${stale} written\n`
);
